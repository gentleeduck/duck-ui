// Emit per-package changelog MDX (mapped to docs slug) + /www/changelog index.
import { existsSync } from 'node:fs'
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const APP_ROOT = path.resolve(here, '..')
const REPO_ROOT = path.resolve(APP_ROOT, '../..')
const PKG_DIR = path.join(REPO_ROOT, 'packages')
const CONTENT_DIR = path.join(APP_ROOT, 'content/docs')

// @gentleduck/<name> → docs slug; unmapped packages are skipped.
const SLUG_BY_NAME = {
  'registry-ui': 'duck-ui',
  primitives: 'duck-primitives',
  calendar: 'duck-calendar',
  cli: 'duck-cli',
  gen: 'duck-gen',
  hooks: 'duck-hooks',
  iam: 'duck-iam',
  lazy: 'duck-lazy',
  libs: 'duck-libs',
  motion: 'duck-motion',
  query: 'duck-query',
  upload: 'duck-upload',
  variants: 'duck-variants',
  vim: 'duck-vim',
  ttest: 'duck-ttest',
  state: 'duck-state',
  shortcut: 'duck-shortcut',
  'registry-build': 'duck-registry-build',
}

async function findChangelogs(dir) {
  const out = []
  for (const e of await readdir(dir, { withFileTypes: true })) {
    if (!e.isDirectory() || e.name === 'node_modules') continue
    const sub = path.join(dir, e.name)
    const cl = path.join(sub, 'CHANGELOG.md')
    if (existsSync(cl)) out.push(cl)
    if (e.name === 'wip' || e.name === 'deprecated') {
      out.push(...(await findChangelogs(sub)))
    }
  }
  return out
}

// Escape `<`, `{`, `}` outside fenced/inline code so MDX renders changesets prose as text.
function escapeForMdx(text) {
  const lines = text.split('\n')
  let inFence = false
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]
    const trimmed = line.trimStart()
    if (trimmed.startsWith('```') || trimmed.startsWith('~~~')) {
      inFence = !inFence
      continue
    }
    if (inFence) continue
    let out = ''
    let inCode = false
    for (const c of line) {
      if (c === '`') {
        inCode = !inCode
        out += c
        continue
      }
      if (!inCode && (c === '<' || c === '{' || c === '}')) {
        out += `\\${c}`
        continue
      }
      out += c
    }
    lines[i] = out
  }
  return lines.join('\n')
}

const BUMPS = [
  ['major', 'Major Changes'],
  ['minor', 'Minor Changes'],
  ['patch', 'Patch Changes'],
]

// A pending changeset shows as Unreleased until the version PR moves it into CHANGELOG.md and deletes it.
async function readPendingChangesets() {
  const dir = path.join(REPO_ROOT, '.changeset')
  const byName = {}
  if (!existsSync(dir)) return byName
  const files = (await readdir(dir)).filter((f) => f.endsWith('.md') && f !== 'README.md').sort()
  for (const file of files) {
    const m = (await readFile(path.join(dir, file), 'utf8')).match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/)
    if (!m) continue
    const summary = m[2].trim()
    for (const line of m[1].split('\n')) {
      const entry = line.match(/^["']@gentleduck\/([a-z0-9-]+)["']:\s*(major|minor|patch)\s*$/)
      if (!entry) continue
      const [, name, bump] = entry
      byName[name] ??= { major: [], minor: [], patch: [] }
      byName[name][bump].push(summary)
    }
  }
  return byName
}

// A one-line summary is a bullet, as the release writes it; a longer one keeps its own paragraphs and lists, which a
// bullet would fold into one indented block.
function unreleasedSection(pending) {
  if (!pending) return ''
  const groups = BUMPS.filter(([bump]) => pending[bump].length).map(([bump, heading]) => {
    const entries = pending[bump].map((summary) => (summary.includes('\n') ? summary : `- ${summary}`))
    return `### ${heading}\n\n${entries.join('\n\n')}`
  })
  return `## Unreleased\n\nMerged, and out with the next release.\n\n${groups.join('\n\n')}\n\n`
}

const pending = await readPendingChangesets()
const written = []

for (const cl of await findChangelogs(PKG_DIR)) {
  const raw = await readFile(cl, 'utf8')
  const m = raw.match(/^#\s+@gentleduck\/([a-z0-9-]+)\s*$/m)
  if (!m) continue
  const name = m[1]
  const slug = SLUG_BY_NAME[name]
  if (!slug) continue
  const targetDir = path.join(CONTENT_DIR, slug)
  if (!existsSync(targetDir)) continue
  const body = unreleasedSection(pending[name]) + raw.slice(raw.indexOf(m[0]) + m[0].length).trim()
  if (!body) continue
  const frontmatter = `---
title: Changelog
description: Release history for @gentleduck/${name}. Newest releases at the top.
section: Changelog
order: 999
---

`
  const file = path.join(targetDir, 'changelog.mdx')
  await writeFile(file, `${frontmatter + escapeForMdx(body)}\n`, 'utf8')
  written.push({ name, slug })
}

written.sort((a, b) => a.slug.localeCompare(b.slug))

const indexBody = `---
title: Changelogs
description: Per-package release notes. Each package keeps its own version history. Newest releases sit at the top.
section: Changelog
order: 999
---

Each \`@gentleduck/*\` package keeps its own changelog generated by changesets. New entries are always appended at the top so the most recent release is the first thing you read.

| Package | Changelog |
|---|---|
${written.map((r) => `| \`@gentleduck/${r.name}\` | [/${r.slug}/changelog](/${r.slug}/changelog) |`).join('\n')}
`

const wwwDir = path.join(CONTENT_DIR, 'www')
if (!existsSync(wwwDir)) await mkdir(wwwDir, { recursive: true })
await writeFile(path.join(wwwDir, 'changelog.mdx'), indexBody, 'utf8')

console.log(`[changelogs] wrote ${written.length} per-package changelogs + /www/changelog index`)
